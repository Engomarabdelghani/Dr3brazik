#!/usr/bin/env node
/**
 * Reads scripts/products.csv and writes src/data/generated/<category>.ts + index.ts.
 *
 * Usage:  node scripts/generate-products.mjs
 * (also runs automatically before `npm run dev` and `npm run build` — see package.json)
 *
 * This is the ONLY file you should regenerate from — never hand-edit anything
 * inside src/data/generated/, since running this script again will overwrite it.
 * To add/edit/remove products, edit scripts/products.csv (open it in Excel,
 * Google Sheets, or any text editor) and re-run this script.
 */
import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const CSV_PATH = path.join(__dirname, 'products.csv');
const OUT_DIR = path.join(__dirname, '..', 'src', 'data', 'generated');

// ---------- tiny CSV parser (handles quoted fields, commas & newlines inside quotes) ----------
function parseCsv(text) {
  const rows = [];
  let row = [];
  let field = '';
  let inQuotes = false;

  for (let i = 0; i < text.length; i++) {
    const c = text[i];
    if (inQuotes) {
      if (c === '"') {
        if (text[i + 1] === '"') { field += '"'; i++; }
        else inQuotes = false;
      } else field += c;
    } else if (c === '"') {
      inQuotes = true;
    } else if (c === ',') {
      row.push(field); field = '';
    } else if (c === '\n' || c === '\r') {
      if (c === '\r' && text[i + 1] === '\n') i++;
      row.push(field); field = '';
      if (row.length > 1 || row[0] !== '') rows.push(row);
      row = [];
    } else {
      field += c;
    }
  }
  if (field !== '' || row.length) { row.push(field); rows.push(row); }

  const header = rows[0];
  return rows.slice(1).filter((r) => r.some((v) => v.trim() !== '')).map((r) =>
    Object.fromEntries(header.map((h, i) => [h.trim(), (r[i] ?? '').trim()]))
  );
}

// ---------- helpers ----------
const slugify = (s) => s.toLowerCase().trim().replace(/[^a-z0-9]+/g, '-').replace(/(^-|-$)/g, '');
const splitList = (s) => (s ? s.split(';').map((v) => v.trim()).filter(Boolean) : []);
const toBool = (s) => ['yes', 'true', '1'].includes((s || '').toLowerCase());
const toNum = (s) => (s === '' || s === undefined ? undefined : Number(s));

function resolveImage(token) {
  if (token.startsWith('img:')) {
    // Placeholder shorthand for products without real photos yet.
    return `https://picsum.photos/seed/${token.slice(4)}/900/1100`;
  }
  return token; // real URL (Cloudinary or otherwise) — used as-is
}

function rowToProduct(row) {
  const concern = splitList(row.concern);
  return {
    id: row.id || `p-${slugify(row.name)}`,
    name: row.name,
    ...(row.name_ar ? { nameAr: row.name_ar } : {}),
    slug: slugify(row.name),
    category: row.category,
    ...(row.subcategory ? { subcategory: row.subcategory } : {}),
    brand: row.brand,
    price: toNum(row.price) ?? 0,
    ...(row.old_price ? { oldPrice: toNum(row.old_price) } : {}),
    currency: row.currency || 'EGP',
    rating: toNum(row.rating) ?? 0,
    reviewCount: toNum(row.review_count) ?? 0,
    images: splitList(row.images).map(resolveImage),
    shortDescription: row.short_description || '',
    description: row.description || '',
    ingredients: splitList(row.ingredients),
    benefits: splitList(row.benefits),
    inStock: row.in_stock === '' ? true : toBool(row.in_stock),
    ...(toBool(row.is_new) ? { isNew: true } : {}),
    ...(toBool(row.is_featured) ? { isFeatured: true } : {}),
    ...(toBool(row.is_flash_sale) ? { isFlashSale: true } : {}),
    ...(row.discount_percent ? { discountPercent: toNum(row.discount_percent) } : {}),
    tags: splitList(row.tags),
    ...(concern.length ? { attributes: { concern } } : {}),
  };
}

// ---------- main ----------
if (!existsSync(CSV_PATH)) {
  console.error(`✗ Could not find ${CSV_PATH}`);
  process.exit(1);
}

const rows = parseCsv(readFileSync(CSV_PATH, 'utf-8'));
const byCategory = {};
for (const row of rows) {
  if (!row.category) {
    console.warn(`⚠ Skipping row with no category: ${row.name || '(unnamed)'}`);
    continue;
  }
  (byCategory[row.category] ??= []).push(rowToProduct(row));
}

mkdirSync(OUT_DIR, { recursive: true });

const categoryVarName = (cat) => `${cat.replace(/[^a-zA-Z0-9]/g, '_')}Products`;

for (const [category, products] of Object.entries(byCategory)) {
  const varName = categoryVarName(category);
  const body = `// AUTO-GENERATED by scripts/generate-products.mjs — do not edit by hand.\n` +
    `// Edit scripts/products.csv instead, then run: npm run catalog\n` +
    `import type { Product } from '../../types';\n\n` +
    `export const ${varName}: Product[] = ${JSON.stringify(products, null, 2)};\n`;
  writeFileSync(path.join(OUT_DIR, `${category}.ts`), body);
}

const indexBody =
  `// AUTO-GENERATED by scripts/generate-products.mjs — do not edit by hand.\n` +
  `import type { Product } from '../../types';\n` +
  Object.keys(byCategory).map((cat) => `import { ${categoryVarName(cat)} } from './${cat}';\n`).join('') +
  `\nexport const products: Product[] = [\n` +
  Object.keys(byCategory).map((cat) => `  ...${categoryVarName(cat)},`).join('\n') +
  `\n];\n`;
writeFileSync(path.join(OUT_DIR, 'index.ts'), indexBody);

const total = Object.values(byCategory).reduce((n, arr) => n + arr.length, 0);
console.log(`✓ Generated ${total} products across ${Object.keys(byCategory).length} categories → src/data/generated/`);
